func TestNormalise(t *testing.T) {
	ok := map[string]string{
		"forge":           "forge",
		"forge.mpd.test":  "forge",
		"  Forge ":        "forge",
		"WARP.MPD.TEST":   "warp",
		"runner-1":        "runner-1",
		"devoci.mpd.test": "devoci",
	}
	for in, want := range ok {
		got, err := Normalise(in)
		if err != nil {
			t.Errorf("Normalise(%q) errored: %v", in, err)
			continue
		}
		if got != want {
			t.Errorf("Normalise(%q) = %q, want %q", in, got, want)
		}
	}

	bad := []string{
		"",                  // empty
		"126",               // VM zone (3-digit)
		"099",               // VM zone even though not a managed id
		"bad_name",          // charset (underscore)
		"-lead",             // leading hyphen
		"trail-",            // trailing hyphen
		"forge.example.com", // outside mpd.test
		"a.b.mpd.test",      // more than one label under mpd.test
	}
	for _, in := range bad {
		if got, err := Normalise(in); err == nil {
			t.Errorf("Normalise(%q) = %q, want error", in, got)
		}
	}
}

func TestValidateIP(t *testing.T) {
	for _, ip := range []string{"10.1.10.100", "10.0.0.1", "::1", "fe80::1"} {
		if err := ValidateIP(ip); err != nil {
			t.Errorf("ValidateIP(%q) rejected a valid address: %v", ip, err)
		}
	}
	for _, ip := range []string{"forge", "1.2.3", "999.1.1.1", "10.0.0.0/24", ""} {
		if err := ValidateIP(ip); err == nil {
			t.Errorf("ValidateIP(%q) accepted an invalid address", ip)
		}
	}
}

